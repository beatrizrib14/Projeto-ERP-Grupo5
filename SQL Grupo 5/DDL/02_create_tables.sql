-- ITEM_ORDEM_SERVIÇO  [Manutenção e operações]
CREATE TABLE item_ordem_servico (
    id_item_os           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_os                INTEGER NOT NULL,
    id_servico           INTEGER,
    id_material          INTEGER,
    quantidade           NUMERIC(12,3) NOT NULL,
    valor_unitario       NUMERIC(14,2),
    valor_total          NUMERIC(14,2),
    CONSTRAINT pk_item_ordem_servico PRIMARY KEY (id_item_os),
    CONSTRAINT ck_item_os_tipo CHECK ((id_servico IS NULL) <> (id_material IS NULL)),
