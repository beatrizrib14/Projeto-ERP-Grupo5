-- Projeto Integrador — Modelagem de Dados | Grupo 5 | UNICID
-- ERP de manutenção e reparo de máquinas extrusoras balão
-- SGBD: PostgreSQL 16 (UTF8)

-- 02 — CREATE TABLE (35 tabelas), PK, FK, NOT NULL, UNIQUE, CHECK, DEFAULT e índices
-- Ordem: tabelas sem dependência primeiro.

SET client_encoding='UTF8';

-- CLIENTE  [Manutenção e operações]
CREATE TABLE cliente (
    id_cliente           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    razao_nome           VARCHAR(120),
    cpf_cnpj             VARCHAR(18) NOT NULL,
    endereco             VARCHAR(200),
    telefone             VARCHAR(20),
    email                VARCHAR(120),
    status               VARCHAR(30),
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_cpf_cnpj UNIQUE (cpf_cnpj)
);

-- MÁQUINA  [Manutenção e operações]
CREATE TABLE maquina (
    id_maquina           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cliente           INTEGER NOT NULL,
    fabricante_modelo    VARCHAR(120),
    num_serie            VARCHAR(40) NOT NULL,
    descricao            VARCHAR(255),
    CONSTRAINT pk_maquina PRIMARY KEY (id_maquina),
    CONSTRAINT uq_maquina_num_serie UNIQUE (num_serie)
);

-- TERCEIRIZADA  [Terceirização]
CREATE TABLE terceirizada (
    id_terceirizada      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    razao_social         VARCHAR(120),
    cnpj                 VARCHAR(18) NOT NULL,
    especialidade        VARCHAR(120),
    contato              VARCHAR(120),
    telefone             VARCHAR(20),
    endereco             VARCHAR(200),
    CONSTRAINT pk_terceirizada PRIMARY KEY (id_terceirizada),
    CONSTRAINT uq_terceirizada_cnpj UNIQUE (cnpj)
);

-- SERVIÇO  [Manutenção e operações]
CREATE TABLE servico (
    id_servico           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome                 VARCHAR(120),
    descricao            VARCHAR(255),
    valor_padrao         NUMERIC(14,2),
    CONSTRAINT pk_servico PRIMARY KEY (id_servico),
    CONSTRAINT ck_servico_valor_padrao_nn CHECK (valor_padrao IS NULL OR valor_padrao >= 0)
);

-- MATERIAL  [Compras e estoque]
CREATE TABLE material (
    id_material          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    descricao            VARCHAR(255),
    unidade              VARCHAR(10),
    estoque_minimo       NUMERIC(12,3),
    CONSTRAINT pk_material PRIMARY KEY (id_material),
    CONSTRAINT ck_material_estoque_minimo CHECK (estoque_minimo IS NULL OR estoque_minimo >= 0)
);

-- CONTA_FINANCEIRA  [Financeiro]
CREATE TABLE conta_financeira (
    id_conta_fin         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome                 VARCHAR(120),
    tipo                 VARCHAR(20) NOT NULL,
    saldo_atual          NUMERIC(14,2),
    CONSTRAINT pk_conta_financeira PRIMARY KEY (id_conta_fin),
    CONSTRAINT ck_conta_fin_tipo CHECK (tipo IN ('BANCO','CAIXA'))
);

-- IMPOSTO  [Financeiro]
CREATE TABLE imposto (
    id_imposto           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo                 VARCHAR(60),
    aliquota             NUMERIC(6,3),
    base_calculo         NUMERIC(14,2),
    valor                NUMERIC(14,2),
    competencia          DATE,
    CONSTRAINT pk_imposto PRIMARY KEY (id_imposto),
    CONSTRAINT ck_imposto_competencia CHECK (competencia IS NULL OR EXTRACT(DAY FROM competencia) = 1),
    CONSTRAINT ck_imposto_valor_nn CHECK (valor IS NULL OR valor >= 0),
    CONSTRAINT ck_imposto_base_calculo_nn CHECK (base_calculo IS NULL OR base_calculo >= 0)
);

-- DESPESA  [Financeiro]
CREATE TABLE despesa (
    id_despesa           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    categoria            VARCHAR(60),
    descricao            VARCHAR(255),
    valor                NUMERIC(14,2),
    data                 DATE,
    CONSTRAINT pk_despesa PRIMARY KEY (id_despesa),
    CONSTRAINT ck_despesa_valor_nn CHECK (valor IS NULL OR valor >= 0)
);

-- FORNECEDOR  [Compras e estoque]
CREATE TABLE fornecedor (
    id_fornecedor        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    razao_social         VARCHAR(120),
    cnpj                 VARCHAR(18),
    endereco             VARCHAR(200),
    telefone             VARCHAR(20),
    contato              VARCHAR(120),
    CONSTRAINT pk_fornecedor PRIMARY KEY (id_fornecedor),
    CONSTRAINT uq_fornecedor_cnpj UNIQUE (cnpj)
);

-- FUNCIONÁRIO  [Recursos humanos]
CREATE TABLE funcionario (
    id_funcionario       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome                 VARCHAR(120),
    cpf                  VARCHAR(14) NOT NULL,
    cargo                VARCHAR(60),
    salario_base         NUMERIC(14,2),
    data_admissao        DATE,
    situacao             VARCHAR(30),
    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT uq_funcionario_cpf UNIQUE (cpf),
    CONSTRAINT ck_funcionario_salario_base_nn CHECK (salario_base IS NULL OR salario_base >= 0)
);

-- FOLHA_PAGAMENTO  [Recursos humanos]
CREATE TABLE folha_pagamento (
    id_folha             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_funcionario       INTEGER NOT NULL,
    competencia          DATE,
    salario_bruto        NUMERIC(14,2),
    descontos            NUMERIC(14,2),
    beneficios           NUMERIC(14,2),
    horas_extras         NUMERIC(14,2),
    salario_liquido      NUMERIC(14,2),
    CONSTRAINT pk_folha_pagamento PRIMARY KEY (id_folha),
    CONSTRAINT ck_folha_competencia CHECK (competencia IS NULL OR EXTRACT(DAY FROM competencia) = 1),
    CONSTRAINT ck_folha_pagamento_salario_bruto_nn CHECK (salario_bruto IS NULL OR salario_bruto >= 0),
    CONSTRAINT ck_folha_pagamento_descontos_nn CHECK (descontos IS NULL OR descontos >= 0),
    CONSTRAINT ck_folha_pagamento_beneficios_nn CHECK (beneficios IS NULL OR beneficios >= 0),
    CONSTRAINT ck_folha_pagamento_horas_extras_nn CHECK (horas_extras IS NULL OR horas_extras >= 0),
    CONSTRAINT ck_folha_pagamento_salario_liquido_nn CHECK (salario_liquido IS NULL OR salario_liquido >= 0)
);

-- ENCARGO  [Recursos humanos]
CREATE TABLE encargo (
    id_encargo           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_folha             INTEGER NOT NULL,
    tipo                 VARCHAR(20),
    base_calculo         NUMERIC(14,2),
    valor                NUMERIC(14,2),
    CONSTRAINT pk_encargo PRIMARY KEY (id_encargo),
    CONSTRAINT ck_encargo_tipo CHECK (tipo IS NULL OR tipo IN ('INSS','FGTS')),
    CONSTRAINT ck_encargo_base_calculo_nn CHECK (base_calculo IS NULL OR base_calculo >= 0),
    CONSTRAINT ck_encargo_valor_nn CHECK (valor IS NULL OR valor >= 0)
);

-- BENEFÍCIO  [Recursos humanos]
CREATE TABLE beneficio (
    id_beneficio         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome                 VARCHAR(120),
    tipo                 VARCHAR(60),
    valor_padrao         NUMERIC(14,2),
    CONSTRAINT pk_beneficio PRIMARY KEY (id_beneficio),
    CONSTRAINT ck_beneficio_valor_padrao_nn CHECK (valor_padrao IS NULL OR valor_padrao >= 0)
);

-- CAPITAL_EMERGÊNCIA  [Financeiro]
CREATE TABLE capital_emergencia (
    id_capital           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_conta_fin         INTEGER NOT NULL,
    valor_reserva        NUMERIC(14,2),
    saldo_reserva        NUMERIC(14,2),
    data_definicao       DATE,
    situacao             VARCHAR(30),
    CONSTRAINT pk_capital_emergencia PRIMARY KEY (id_capital),
    CONSTRAINT ck_capital_emergencia_valor_reserva_nn CHECK (valor_reserva IS NULL OR valor_reserva >= 0),
    CONSTRAINT ck_capital_emergencia_saldo_reserva_nn CHECK (saldo_reserva IS NULL OR saldo_reserva >= 0)
);

-- SOLICITAÇÃO  [Manutenção e operações]
CREATE TABLE solicitacao (
    id_solicitacao       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cliente           INTEGER NOT NULL,
    id_maquina           INTEGER NOT NULL,
    id_funcionario       INTEGER,
