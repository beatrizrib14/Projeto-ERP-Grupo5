    id_maquina           INTEGER NOT NULL,
    id_terceirizada      INTEGER,
    id_os                INTEGER,
    id_funcionario       INTEGER NOT NULL,
    tipo                 VARCHAR(20) NOT NULL,
    data_hora            TIMESTAMP,
