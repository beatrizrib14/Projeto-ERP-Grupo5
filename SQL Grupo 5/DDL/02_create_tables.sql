    CONSTRAINT ck_item_ordem_servico_valor_unitario_nn CHECK (valor_unitario IS NULL OR valor_unitario >= 0),
    CONSTRAINT ck_item_ordem_servico_valor_total_nn CHECK (valor_total IS NULL OR valor_total >= 0)
);

-- CONTA_A_RECEBER  [Financeiro]
CREATE TABLE conta_a_receber (
    id_conta_receber     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_os                INTEGER NOT NULL,
    valor                NUMERIC(14,2),
    percentual           NUMERIC(5,2),
    parcela              VARCHAR(20) NOT NULL,
    data_vencimento      DATE,
    situacao             VARCHAR(30),
    CONSTRAINT pk_conta_a_receber PRIMARY KEY (id_conta_receber),
    CONSTRAINT uq_conta_receber_os_parcela UNIQUE (id_os, parcela),
    CONSTRAINT ck_cr_parcela CHECK (parcela IN ('ENTRADA','FINAL')),
    CONSTRAINT ck_cr_percentual CHECK (percentual IS NULL OR percentual BETWEEN 0 AND 100),
    CONSTRAINT ck_conta_a_receber_valor_nn CHECK (valor IS NULL OR valor >= 0)
);

-- RECEBIMENTO  [Financeiro]
CREATE TABLE recebimento (
    id_recebimento       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_conta_receber     INTEGER NOT NULL,
    numero_parcela       INTEGER,
    valor_pago           NUMERIC(14,2),
    data_pagamento       DATE,
    forma_pagamento      VARCHAR(30),
    multa                NUMERIC(14,2) DEFAULT 0,
    juros                NUMERIC(14,2) DEFAULT 0,
    CONSTRAINT pk_recebimento PRIMARY KEY (id_recebimento),
    CONSTRAINT ck_recebimento_valores CHECK (COALESCE(valor_pago,0) >= 0 AND multa >= 0 AND juros >= 0),
    CONSTRAINT ck_recebimento_parcela CHECK (numero_parcela IS NULL OR numero_parcela >= 1)
);

-- CONTA_A_PAGAR  [Financeiro]
CREATE TABLE conta_a_pagar (
    id_conta_pagar       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_folha             INTEGER,
    id_contratacao       INTEGER,
    id_imposto           INTEGER,
    id_despesa           INTEGER,
    descricao            VARCHAR(255),
    origem_tipo          VARCHAR(20),
    valor_origem         NUMERIC(14,2),
    data_vencimento      DATE,
    situacao             VARCHAR(30),
    CONSTRAINT pk_conta_a_pagar PRIMARY KEY (id_conta_pagar),
    CONSTRAINT uq_conta_a_pagar_id_contratacao UNIQUE (id_contratacao),
    CONSTRAINT uq_conta_a_pagar_id_imposto UNIQUE (id_imposto),
    CONSTRAINT uq_conta_a_pagar_id_despesa UNIQUE (id_despesa),
    CONSTRAINT ck_cap_origem CHECK ((origem_tipo='FOLHA' AND id_folha IS NOT NULL AND id_contratacao IS NULL AND id_imposto IS NULL AND id_despesa IS NULL) OR (origem_tipo='CONTRATAÇÃO' AND id_contratacao IS NOT NULL AND id_folha IS NULL AND id_imposto IS NULL AND id_despesa IS NULL) OR (origem_tipo='IMPOSTO' AND id_imposto IS NOT NULL AND id_folha IS NULL AND id_contratacao IS NULL AND id_despesa IS NULL) OR (origem_tipo='DESPESA' AND id_despesa IS NOT NULL AND id_folha IS NULL AND id_contratacao IS NULL AND id_imposto IS NULL) OR (origem_tipo='COMPRA' AND id_folha IS NULL AND id_contratacao IS NULL AND id_imposto IS NULL AND id_despesa IS NULL)),
    CONSTRAINT ck_conta_a_pagar_valor_origem_nn CHECK (valor_origem IS NULL OR valor_origem >= 0)
);

