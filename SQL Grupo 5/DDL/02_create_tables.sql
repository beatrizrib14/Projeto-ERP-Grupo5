    data_solicitacao     DATE,
    status               VARCHAR(30),
    CONSTRAINT pk_solicitacao PRIMARY KEY (id_solicitacao)
);

-- ORÇAMENTO  [Manutenção e operações]
CREATE TABLE orcamento (
    id_orcamento         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_solicitacao       INTEGER NOT NULL,
    versao               INTEGER NOT NULL DEFAULT 1,
    valor_total          NUMERIC(14,2),
    prazo_dias           INTEGER,
    data_emissao         DATE,
    data_decisao         DATE,
    situacao             VARCHAR(20),
    CONSTRAINT pk_orcamento PRIMARY KEY (id_orcamento),
    CONSTRAINT uq_orcamento_solicitacao_versao UNIQUE (id_solicitacao, versao),
    CONSTRAINT ck_orcamento_versao CHECK (versao >= 1),
    CONSTRAINT ck_orcamento_situacao CHECK (situacao IS NULL OR situacao IN ('APROVADO','RECUSADO')),
    CONSTRAINT ck_orcamento_prazo CHECK (prazo_dias IS NULL OR prazo_dias >= 0),
    CONSTRAINT ck_orcamento_valor_total_nn CHECK (valor_total IS NULL OR valor_total >= 0)
);

-- ORDEM_SERVIÇO  [Manutenção e operações]
CREATE TABLE ordem_servico (
