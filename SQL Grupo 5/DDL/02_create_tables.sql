    resultado            VARCHAR(40),
    motivo_reprovacao    TEXT,
    CONSTRAINT pk_inspecao PRIMARY KEY (id_inspecao)
);

-- COTAÇÃO  [Terceirização]
CREATE TABLE cotacao (
    id_cotacao           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_os                INTEGER NOT NULL,
    id_terceirizada      INTEGER NOT NULL,
    valor_proposto       NUMERIC(14,2),
    prazo_dias           INTEGER,
    data_cotacao         DATE,
    situacao             VARCHAR(20),
    CONSTRAINT pk_cotacao PRIMARY KEY (id_cotacao),
    CONSTRAINT ck_cotacao_situacao CHECK (situacao IS NULL OR situacao IN ('APROVADA','RECUSADA')),
    CONSTRAINT ck_cotacao_prazo CHECK (prazo_dias IS NULL OR prazo_dias >= 0),
    CONSTRAINT ck_cotacao_valor_proposto_nn CHECK (valor_proposto IS NULL OR valor_proposto >= 0)
