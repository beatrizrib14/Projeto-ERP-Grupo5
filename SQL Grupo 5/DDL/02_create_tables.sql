    data_contratacao     DATE,
    valor_contratado     NUMERIC(14,2),
    prazo_dias           INTEGER,
    servico_contratado   VARCHAR(255),
    CONSTRAINT pk_contratacao PRIMARY KEY (id_contratacao),
    CONSTRAINT uq_contratacao_id_cotacao UNIQUE (id_cotacao),
    CONSTRAINT ck_contratacao_prazo CHECK (prazo_dias IS NULL OR prazo_dias >= 0),
    CONSTRAINT ck_contratacao_valor_contratado_nn CHECK (valor_contratado IS NULL OR valor_contratado >= 0)
);

-- MOVIMENTAÇÃO_MÁQUINA  [Manutenção e operações]
CREATE TABLE movimentacao_maquina (
